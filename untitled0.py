import pandas as pd
import plotly.express as px
from dash import Dash, dcc, html, Input, Output

url = "https://raw.githubusercontent.com/Coding-with-Adam/Dash-by-Plotly/master/Other/Monterrey/airbnb.csv"
df = pd.read_csv(url)

required_columns = ['latitude', 'longitude', 'price', 'minimum_nights', 'neighbourhood']
missing = [c for c in required_columns if c not in df.columns]
if missing:
    raise ValueError(f"Missing columns in dataset: {missing}")

for col in ['latitude', 'longitude', 'price', 'minimum_nights']:
    if col == 'price':
        df[col] = pd.to_numeric(df[col].astype(str).str.replace(r'[^\d.]', '', regex=True), errors='coerce')
    else:
        df[col] = pd.to_numeric(df[col], errors='coerce')

df['neighbourhood'] = df['neighbourhood'].astype(str).str.strip()
df = df.dropna(subset=required_columns)
df = df[
    df['latitude'].between(-90, 90) &
    df['longitude'].between(-180, 180) &
    (df['price'] > 0)
]

if df.empty:
    raise ValueError("No valid records found in dataset.")

app = Dash(__name__)

neighbourhoods = sorted(df['neighbourhood'].unique())
min_price = int(df['price'].min())
max_price = int(df['price'].quantile(0.95))
if max_price <= min_price:
    max_price = int(df['price'].max())

step_val = max(1, (max_price - min_price) // 5)
slider_marks = {p: f"${p}" for p in range(min_price, max_price + 1, step_val)}

app.layout = html.Div(
    style={'fontFamily': 'sans-serif', 'maxWidth': '1200px', 'margin': '0 auto', 'padding': '20px'},
    children=[
        html.H1(
            children='Airbnb Listings in Monterrey',
            style={'textAlign': 'center', 'color': '#111'}
        ),
        html.Div(
            style={
                'display': 'flex',
                'flexWrap': 'wrap',
                'gap': '30px',
                'alignItems': 'center',
                'justifyContent': 'center',
                'padding': '15px',
                'backgroundColor': '#f8f9fa',
                'borderRadius': '8px',
                'marginBottom': '20px'
            },
            children=[
                html.Div(style={'minWidth': '280px'}, children=[
                    html.Label("Select Neighbourhood:", style={'fontWeight': 'bold', 'display': 'block', 'marginBottom': '6px'}),
                    dcc.Dropdown(
                        id='neighbourhood-dropdown',
                        options=[{'label': 'All Neighbourhoods', 'value': 'ALL'}] + [
                            {'label': n, 'value': n} for n in neighbourhoods
                        ],
                        value='ALL',
                        clearable=False
                    )
                ]),
                html.Div(style={'minWidth': '350px', 'flex': '1'}, children=[
                    html.Label("Maximum Price per Night ($):", style={'fontWeight': 'bold', 'display': 'block', 'marginBottom': '6px'}),
                    dcc.Slider(
                        id='price-slider',
                        min=min_price,
                        max=max_price,
                        value=max_price,
                        marks=slider_marks,
                        tooltip={"placement": "bottom", "always_visible": True}
                    )
                ])
            ]
        ),
        dcc.Graph(id='airbnb-map')
    ]
)

@app.callback(
    Output('airbnb-map', 'figure'),
    Input('neighbourhood-dropdown', 'value'),
    Input('price-slider', 'value')
)
def update_map(selected_neighbourhood, selected_max_price):
    filtered_df = df[df['price'] <= selected_max_price]

    if selected_neighbourhood != 'ALL':
        filtered_df = filtered_df[filtered_df['neighbourhood'] == selected_neighbourhood]

    center_lat = filtered_df['latitude'].mean() if not filtered_df.empty else 25.6866
    center_lon = filtered_df['longitude'].mean() if not filtered_df.empty else -100.3161
    hover_col = 'name' if 'name' in filtered_df.columns else None

    if hasattr(px, 'scatter_map'):
        fig = px.scatter_map(
            filtered_df,
            lat='latitude',
            lon='longitude',
            hover_name=hover_col,
            hover_data=['neighbourhood', 'price', 'minimum_nights'],
            color='price',
            color_continuous_scale=px.colors.cyclical.IceFire,
            center={'lat': center_lat, 'lon': center_lon},
            zoom=11,
            height=600
        )
        fig.update_layout(map_style="carto-positron")
    else:
        fig = px.scatter_mapbox(
            filtered_df,
            lat='latitude',
            lon='longitude',
            hover_name=hover_col,
            hover_data=['neighbourhood', 'price', 'minimum_nights'],
            color='price',
            color_continuous_scale=px.colors.cyclical.IceFire,
            center={'lat': center_lat, 'lon': center_lon},
            zoom=11,
            height=600
        )
        fig.update_layout(mapbox_style="carto-positron")

    area_label = "All Neighbourhoods" if selected_neighbourhood == 'ALL' else selected_neighbourhood
    fig.update_layout(
        margin={"r": 0, "t": 45, "l": 0, "b": 0},
        title=f"{area_label} — Listings up to ${selected_max_price} ({len(filtered_df)} found)"
    )
    return fig

if __name__ == '__main__':
    app.run(jupyter_mode='inline', port=8052)